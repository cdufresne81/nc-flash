"""Replay the reference applier's recorded verdicts through src/ecu/ncflash_patch.py.

Each tests/fixtures/ncflash_patch/*.vectors.json was generated by make_vectors.py
with nc-flash-re tools/ncflash_apply.py (the reference NC Flash ports). Every
case must give the same verdict and the same output bytes here.
"""

import hashlib
import importlib.util
import json
from functools import lru_cache
from pathlib import Path

import pytest

from src.ecu import ncflash_patch as N

REPO = Path(__file__).resolve().parent.parent
FIX = REPO / "tests" / "fixtures" / "ncflash_patch"
VECTOR_FILES = sorted(FIX.glob("*.vectors.json"))


def _module():
    spec = importlib.util.spec_from_file_location(
        "make_vectors", FIX / "make_vectors.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


MV = _module()
MV.r0 = lru_cache(maxsize=None)(MV.r0)  # one fresh Romdrop image per run


def _patch_bytes(name: str, sha: str) -> bytes:
    for cand in [FIX / name, *(REPO / "patches").rglob(name)]:
        if cand.is_file() and hashlib.sha256(cand.read_bytes()).hexdigest() == sha:
            return cand.read_bytes()
    raise FileNotFoundError(f"{name} with sha256 {sha[:16]}")


@lru_cache(maxsize=None)
def _load(vf: Path):
    doc = json.loads(vf.read_bytes())
    raw = _patch_bytes(doc["patch_file"], doc["patch_sha256"])
    patch = N.load_patch(raw, doc["patch_sha256"])
    consents = [c["id"] for c in patch.consents]
    installed = N.apply_patch(MV.r0(), patch, set(consents)).output
    return doc, patch, installed


def _cases():
    for vf in VECTOR_FILES:
        doc = json.loads(vf.read_bytes())
        for i, v in enumerate(doc["vectors"]):
            yield pytest.param(vf, i, id=f"{vf.stem}:{v['name']}:{len(v['consent'])}")


def test_vector_files_exist():
    assert VECTOR_FILES


@pytest.mark.parametrize("vf, i", list(_cases()))
def test_same_verdict_and_output_as_the_reference(vf, i):
    doc, patch, installed = _load(vf)
    v = doc["vectors"][i]
    res = N.apply_patch(MV.build(v, installed), patch, set(v["consent"]))
    got = hashlib.sha256(res.output).hexdigest() if res.output else None
    assert (res.verdict, got) == (v["verdict"], v["output_sha256"]), [
        (f.level, f.message) for f in res.report.rows if f.level != "INFO"
    ]
